// Regenerates the customer-portal preview pages from the REAL portal templates.
//
// It reuses the synthetic fixture that tools/shots/portal-contract.test.mjs already renders
// (made-up client, people and computers), runs it through PHP, and rewrites the asset URLs so the
// pages open straight from disk. Nothing here reads a database, a settings file or the network.
//
//   node tools/shots/preview/build-portal.mjs
//
// Needs `php` on PATH. Output: portal-home.html, portal-devices.html, portal-ticket.html and
// portal-signin.html next to this file.
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const source = await readFile(path.join(ROOT, 'tools/shots/portal-contract.test.mjs'), 'utf8');
const match = source.match(/const FIXTURE_PHP = String\.raw`([\s\S]*?)\n`;/);
if (!match) throw new Error('Could not find FIXTURE_PHP in portal-contract.test.mjs');

const scratch = await mkdtemp(path.join(tmpdir(), 'safeharbor-preview-'));
const fixture = path.join(scratch, 'fixture.php');
await writeFile(fixture, match[1], 'utf8');

// Made-up names only: the preview is published with a public repository.
const NAMES = [['Frank at 8 West Lifestyle', 'Priya Anand'], ['8 West Lifestyle', 'Harbor Dental'], ['Synthetic Employee', 'Dana Whitfield'], ['>Frank<', '>Priya Anand<']];
const PAGES = { home: 'portal-home.html', devices: 'portal-devices.html', ticket: 'portal-ticket.html', login: 'portal-signin.html' };

try {
  for (const [fixtureName, file] of Object.entries(PAGES)) {
    const result = spawnSync('php', [fixture, path.join(ROOT, 'app/lib/portal_data.php'), path.join(ROOT, 'app/lib/portal_render.php'), fixtureName], { encoding: 'utf8' });
    if (result.status !== 0) throw new Error(`PHP fixture ${fixtureName} failed: ${result.stderr}`);
    let html = result.stdout
      .replace(/(href|src)="\/assets\//g, '$1="../../../app/public/assets/')
      .replace(/(href|src)="\/portal\/[^"]*"/g, '$1="#"')
      .replace(/<script src="[^"]*portal-[a-z-]+\.js[^"]*" defer><\/script>\n?/g, '');
    for (const [from, to] of NAMES) html = html.split(from).join(to);
    html = html.replace('</head>', '<meta name="robots" content="noindex">\n<script src="preview.js" defer></script>\n</head>');
    html = `<!-- Generated by build-portal.mjs from the real portal templates. Synthetic data only. -->\n${html}`;
    await writeFile(path.join(HERE, file), html, 'utf8');
    console.log('wrote', file);
  }
} finally {
  await rm(scratch, { recursive: true, force: true });
}
