// Regenerates the customer-portal preview pages from the REAL portal templates.
//
// It reuses the synthetic fixture that tools/shots/portal-contract.test.mjs already renders
// (made-up client, people and computers), runs it through PHP, and rewrites the asset URLs so the
// pages open straight from disk. Nothing here reads a database, a settings file or the network.
//
//   node tools/shots/preview/build-portal.mjs
//
// Needs `php` on PATH. Output: portal-home.html, portal-devices.html, portal-signin.html and the request
// page at four steps (portal-ticket*.html) next to this file.
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const source = await readFile(path.join(ROOT, 'tools/shots/portal-contract.test.mjs'), 'utf8');
const match = source.match(/const FIXTURE_PHP = String\.raw`([\s\S]*?)\n`;/);
if (!match) throw new Error('Could not find FIXTURE_PHP in portal-contract.test.mjs');

// One preview-only variant on top of the test fixture: the owner's Home before any computer exists.
const fixtureSource = match[1]
  .replace(/    case 'home':\r?\n/, "    case 'homesetup':\n    case 'home':\n")
  .replace("        portal_render_home($context,", "        if($argv[3]==='homesetup')$homeDevices['items']=[];\n        portal_render_home($context,");
if (!fixtureSource.includes("case 'homesetup'") || !fixtureSource.includes("$homeDevices['items']=[]")) throw new Error('Could not add the no-computers Home variant to the fixture');

const scratch = await mkdtemp(path.join(tmpdir(), 'safeharbor-preview-'));
const fixture = path.join(scratch, 'fixture.php');
await writeFile(fixture, fixtureSource, 'utf8');

// Made-up names only: the preview is published with a public repository.
const NAMES = [['8 West Lifestyle', 'Harbor Dental'], ['Synthetic Employee', 'Dana Whitfield']];
const PAGES = { home: 'portal-home.html', homesetup: 'portal-home-first-run.html', homeresolved: 'portal-home-resolved.html',
  homenone: 'portal-home-no-requests.html', homereader: 'portal-home-reader.html', dashboard: 'portal-requests.html', devices: 'portal-devices.html',
  devicesempty: 'portal-devices-first-computer.html', devicesdownload: 'portal-devices-adding.html', ticket: 'portal-ticket.html',
  ticketopen: 'portal-ticket-sent.html', ticketprogress: 'portal-ticket-in-progress.html', ticketresolved: 'portal-ticket-resolved.html', login: 'portal-signin.html' };

// Computer access is rendered by its own controller, run beside stand-in libraries by its PHP test.
const ACCESS = { 'computer-access-admin.html': 'portal-computer-access.html', 'computer-access-admin-link.html': 'portal-computer-access-link.html',
  'computer-access-member.html': 'portal-computer-access-member.html' };

async function publish(rendered, file) {
  let html = rendered
    .replace(/(href|src)="\/assets\//g, '$1="../../../app/public/assets/')
    .replace(/(href|src)="\/portal\/[^"]*"/g, '$1="#"')
    .replace(/<script (?:defer )?src="[^"]*portal-[a-z-]+\.js[^"]*"(?: defer)?><\/script>\n?/g, '');
  for (const [from, to] of NAMES) html = html.split(from).join(to);
  html = html.replace('</head>', '<meta name="robots" content="noindex">\n<script src="preview.js" defer></script>\n</head>');
  // This repository is public: refuse to write a page that still carries a fixture name.
  const leaked = html.match(/frank|lifestyle|gonzalez/i);
  if (leaked) throw new Error(`${file} still contains the fixture name "${leaked[0]}"; add it to NAMES before publishing`);
  html = `<!-- Generated by build-portal.mjs from the real portal templates. Synthetic data only. -->\n${html}`;
  await writeFile(path.join(HERE, file), html, 'utf8');
  console.log('wrote', file);
}

try {
  for (const [fixtureName, file] of Object.entries(PAGES)) {
    const result = spawnSync('php', [fixture, path.join(ROOT, 'app/lib/portal_data.php'), path.join(ROOT, 'app/lib/portal_render.php'), fixtureName], { encoding: 'utf8' });
    if (result.status !== 0) throw new Error(`PHP fixture ${fixtureName} failed: ${result.stderr}`);
    await publish(result.stdout, file);
  }
  const access = spawnSync('php', [path.join(ROOT, 'app/tests/portal_computer_access_test.php')], { encoding: 'utf8', env: { ...process.env, PORTAL_ACCESS_PREVIEW_DIR: scratch } });
  if (access.status !== 0) throw new Error(`Computer access pages failed: ${access.stdout}${access.stderr}`);
  for (const [source, file] of Object.entries(ACCESS)) await publish(await readFile(path.join(scratch, source), 'utf8'), file);
} finally {
  await rm(scratch, { recursive: true, force: true });
}
