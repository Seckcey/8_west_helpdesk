// Inert synthetic previews from the real weekly-summary renderer.
import { spawnSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../../..');
for(const state of ['list','detail']) {
  const rendered=spawnSync('php',[path.join(root,'app/tests/fixtures/portal_summary_display.php'),state,'light'],{encoding:'utf8'});
  if(rendered.status!==0)throw new Error(rendered.stderr);
  const html=rendered.stdout
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,'')
    .replace(/<input\b[^>]*type="hidden"[^>]*>/g,'')
    .replace(/ data-csrf="[^"]*"/g,'')
    .replace(/<form\b[^>]*>/g,'<div>').replace(/<\/form>/g,'</div>')
    .replace(/<button\b/g,'<button disabled')
    .replace(/(href|src)="\/assets\//g,'$1="../../../app/public/assets/')
    .replace(/(href|action)="(?:\/portal[^" ]*|https:[^"]*)"/g,'$1="#"')
    .replace('</head>','<meta name="robots" content="noindex"><script src="preview.js" defer></script></head>');
  await writeFile(path.join(here,`portal-summary-${state}.html`),'<!-- Inert synthetic preview; generated by build-portal-summaries.mjs. -->\n'+html,'utf8');
}
